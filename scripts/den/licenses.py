#!/usr/bin/env python3
"""THIRD_PARTY_LICENSES.md for Epeaky: every Rust crate compiled into the
page's WebAssembly (mls/) and the server's native library (server/native/),
every Elixir package the release carries (server/mix.lock, prod only), and the
Phoenix socket client the page ships. Each with its declared license and the
license texts its package carries.

    scripts/den/licenses.py OUT     (run from the workspace, after mix deps.get)
"""
import glob
import json
import os
import re
import subprocess
import sys

DEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "apps", "cave-den")
OUT = sys.argv[1]

LICENSE_FILES = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)([-._].*)?$", re.I)


def texts(folder):
    out = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if os.path.isfile(path) and LICENSE_FILES.match(name):
            with open(path, encoding="utf-8", errors="replace") as f:
                out.append((name, f.read().strip()))
    return out


def crates(manifest):
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--manifest-path", manifest, "--filter-platform", "wasm32-unknown-unknown" if "/mls/" in manifest else "x86_64-unknown-linux-gnu"],
        stderr=subprocess.DEVNULL))
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    # Normal (not build or dev) dependencies reachable from the root.
    seen, todo = set(), [root]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                todo.append(d["pkg"])
    pkgs = {p["id"]: p for p in meta["packages"]}
    return [pkgs[i] for i in seen if i != root]


TEXTS = {}  # text → its number in the appendix


def ref(body):
    if body not in TEXTS:
        TEXTS[body] = len(TEXTS) + 1
    return TEXTS[body]


def entry(lines, title, source, folder):
    lines.append(f"### {title}")
    if source:
        lines.append(f"Source: {source}")
    found = texts(folder)
    lines.append("License texts: " + (", ".join(f"[{fname}](#text-{ref(body)})" for fname, body in found) if found else "none in the package; its declared license above applies"))
    lines.append("")


def main():
    rust = {}
    for manifest in [os.path.join(DEN, "mls", "Cargo.toml"), os.path.join(DEN, "server", "native", "den_public", "Cargo.toml")]:
        for p in crates(manifest):
            rust[(p["name"], p["version"])] = p
    lock = open(os.path.join(DEN, "server", "mix.lock")).read()
    hex_names = sorted(set(re.findall(r'^\s*"([a-z0-9_]+)": \{:hex', lock, re.M)))
    lines = ["# Third-party licenses", "",
             "Epeaky is MIT OR Apache-2.0 (see LICENSE-MIT, LICENSE-APACHE and NOTICE). It is built",
             "with the packages below, whose licenses and notices follow. Generated by",
             "`scripts/den/licenses.py`; nothing here is GPL or AGPL, and MPL-2.0 code is only in",
             "unmodified crates (hpke-rs).", ""]
    lines += ["## Rust crates (the page's WebAssembly and the server's native library)", ""]
    for (name, version), p in sorted(rust.items()):
        entry(lines, f"{name} {version}: {p.get('license') or 'see its texts'}", p.get("repository"), os.path.dirname(p["manifest_path"]))
    lines += ["## Elixir and Erlang packages (the server)", ""]
    for name in hex_names:
        folder = os.path.join(DEN, "server", "deps", name)
        if not os.path.isdir(folder):
            continue
        meta = open(os.path.join(folder, "hex_metadata.config")).read() if os.path.exists(os.path.join(folder, "hex_metadata.config")) else ""
        lic = ", ".join(re.findall(r'<<"([^"]+)">>', (re.search(r"\{<<\"licenses\">>,\[(.*?)\]\}", meta, re.S) or [None, ""])[1])) or "see below"
        ver = (re.search(r'\{<<"version">>,<<"([^"]+)">>\}', meta) or [None, ""])[1]
        entry(lines, f"{name} {ver}: {lic}", f"https://hex.pm/packages/{name}", folder)
    lines += ["## Shipped in the page", "",
              "`den/phoenix.mjs`, the Phoenix socket client, from the phoenix package above (MIT).", ""]
    lines += ["## License texts", ""]
    for body, n in sorted(TEXTS.items(), key=lambda x: x[1]):
        lines += [f'<a id="text-{n}"></a>', f"### Text {n}", "", "```", body, "```", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"{len(rust)} crates, {len(hex_names)} Elixir packages -> {OUT}")


main()
